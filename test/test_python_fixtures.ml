(* Responses generated by scripts/gen_fixtures.py and verified there by py_webauthn 2.7.0;
   this library must reach the same conclusions. *)
open! Core
open Webauthn
module U = Yojson.Safe.Util

let now = Time_ns.of_string_with_utc_offset "2026-10-14 12:00:00Z"

let names =
  [ "es256-none-security-key"
  ; "es256-packed-self"
  ; "es256-none-passkey"
  ; "rs256-none"
  ; "rs256-packed-self"
  ]
;;

let challenge json =
  Challenge.of_bytes
    ~issued_at:now
    ~expires_at:(Time_ns.add now Challenge.default_ttl)
    (U.to_string json |> Base64url.decode_exn)
;;

let check name ~ours ~theirs =
  if not (Yojson.Safe.equal ours theirs)
  then
    printf
      "  MISMATCH %s: ours %s, py_webauthn %s\n"
      name
      (Yojson.Safe.to_string ours)
      (Yojson.Safe.to_string theirs)
;;

let%expect_test "same verdicts and fields as py_webauthn" =
  List.iter names ~f:(fun name ->
    let doc = Vectors.json ("python/" ^ name ^ ".json") in
    let rp =
      Relying_party.create
        ~id:(U.member "rp_id" doc |> U.to_string)
        ~origins:[ U.member "origin" doc |> U.to_string ]
        ()
      |> Or_error.ok_exn
    in
    let user_handle = U.member "user_handle" doc |> U.to_string |> Base64url.decode_exn in
    let reg = U.member "registration" doc in
    let response =
      Response.Registration.of_json (U.member "response" reg) |> Or_error.ok_exn
    in
    match
      Registration.verify
        ~user_verification:Required
        rp
        response
        ~challenge:(challenge (U.member "challenge" reg))
        ~now
        ~user_handle
    with
    | Error e -> printf "%s: registration refused %s\n" name (Verify_error.code e)
    | Ok r ->
      let c = r.credential in
      let expected = U.member "expected" reg in
      let e k = U.member k expected in
      printf
        "%s: registered %s (%s)\n"
        name
        (Sexp.to_string [%sexp (Cose.algorithm c.public_key : Cose.Algorithm.t)])
        (Sexp.to_string [%sexp (r.attestation : Attestation.Kind.t)]);
      check
        "credential_id"
        ~ours:(`String (Base64url.encode c.id))
        ~theirs:(e "credential_id");
      (* py_webauthn returns the COSE key bytes as sent; compare decoded keys. *)
      let theirs_key =
        e "credential_public_key"
        |> U.to_string
        |> Base64url.decode_exn
        |> Cose.decode
        |> Or_error.ok_exn
      in
      if not (Cose.equal theirs_key c.public_key)
      then print_endline "  MISMATCH public key";
      check "sign_count" ~ours:(`Int c.sign_count) ~theirs:(e "sign_count");
      check
        "aaguid"
        ~ours:(`String (Authenticator_data.Aaguid.to_string c.aaguid))
        ~theirs:(e "aaguid");
      check "fmt" ~ours:(`String c.attestation_format) ~theirs:(e "fmt");
      check "user_verified" ~ours:(`Bool c.user_verified) ~theirs:(e "user_verified");
      check
        "backup_eligible"
        ~ours:(`Bool c.backup_eligible)
        ~theirs:(e "backup_eligible");
      check "backed_up" ~ours:(`Bool c.backed_up) ~theirs:(e "backed_up");
      let (_ : Credential.t) =
        List.fold
          (U.member "authentications" doc |> U.to_list)
          ~init:c
          ~f:(fun credential a ->
            let response =
              Response.Authentication.of_json (U.member "response" a) |> Or_error.ok_exn
            in
            match
              Authentication.verify
                rp
                response
                ~challenge:(challenge (U.member "challenge" a))
                ~now
                ~credential
            with
            | Error err ->
              printf "  assertion refused %s\n" (Verify_error.code err);
              credential
            | Ok v ->
              let e k = U.member k (U.member "expected" a) in
              printf
                "  assertion ok, count %d, %s\n"
                v.credential.sign_count
                (Sexp.to_string [%sexp (v.sign_count : Authentication.Sign_count.t)]);
              check
                "new_sign_count"
                ~ours:(`Int v.credential.sign_count)
                ~theirs:(e "new_sign_count");
              check
                "user_verified"
                ~ours:(`Bool v.user_verified)
                ~theirs:(e "user_verified");
              check
                "backed_up"
                ~ours:(`Bool v.credential.backed_up)
                ~theirs:(e "backed_up");
              v.credential)
      in
      ());
  [%expect
    {|
    es256-none-security-key: registered Es256 (None_)
      assertion ok, count 1, Advanced
      assertion ok, count 2, Advanced
      assertion ok, count 3, Advanced
    es256-packed-self: registered Es256 (Self)
      assertion ok, count 1, Advanced
    es256-none-passkey: registered Es256 (None_)
      assertion ok, count 0, Not_used
      assertion ok, count 0, Not_used
    rs256-none: registered Rs256 (None_)
      assertion ok, count 1, Advanced
      assertion ok, count 2, Advanced
    rs256-packed-self: registered Rs256 (Self)
      assertion ok, count 1, Advanced
    |}]
;;
